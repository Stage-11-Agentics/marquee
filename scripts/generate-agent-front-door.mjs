#!/usr/bin/env node

import { createHash } from "node:crypto";
import { access, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

import { COMMAND_REGISTRY } from "../cli/registry.mjs";

export const REPOSITORY_ROOT = resolve(import.meta.dirname, "..");
export const MANIFEST_PATH = resolve(REPOSITORY_ROOT, "src/agent-front-door/manifest.json");
export const TEMPLATE_PATH = resolve(REPOSITORY_ROOT, "src/agent-front-door/llms.txt.template");
export const LLMS_OUTPUT_PATH = resolve(REPOSITORY_ROOT, "src/agent-front-door/llms.txt");
export const FULL_OUTPUT_PATH = resolve(REPOSITORY_ROOT, "src/agent-front-door/llms-full.txt");
export const LATENCY_PATH = resolve(REPOSITORY_ROOT, "scripts/latency-baseline.json");
export const BUNDLE_PATH = resolve(REPOSITORY_ROOT, "dist/marquee/index.js");

export const GENERATED_BANNER = `<!-- GENERATED by \`npm run build\`. Do not edit by hand.
     Sources: src/agent-front-door/llms.txt.template, src/agent-front-door/manifest.json,
     cli/registry.mjs, /api/openapi.json, scripts/latency-baseline.json,
     scripts/generate-agent-front-door.mjs. -->\n`;

// Every entry here is fetched by the front-door contract test, so this list is
// specifically the doors a GET opens. `POST /mcp` has its own section in the
// template instead: advertising it as a link would promise a response it
// deliberately does not give.
const MACHINE_DOORS = [
  ["OpenAPI JSON", "/api/openapi.json", "the canonical machine schema and digest source"],
  ["API reference", "/api/docs", "the self-contained rendered operation reference"],
  ["Skill", "/SKILL.md", "the command-oriented workflow an agent can install"],
  ["For agents", "/agenda/agents", "the no-account public schedule surface"],
  ["Full machine context", "/llms-full.txt", "the served documentation bundle"],
];

function canonicalHeader(source, url) {
  return `<!-- Canonical source: ${source}; served at ${url}. -->\n`;
}

async function readManifest() {
  return JSON.parse(await readFile(MANIFEST_PATH, "utf8"));
}

async function readSourceDocuments(manifest) {
  return Promise.all(manifest.map(async (entry) => {
    const sourceText = await readFile(resolve(REPOSITORY_ROOT, entry.source), "utf8");
    return {
      ...entry,
      sourceText,
      servedText: `${canonicalHeader(entry.source, entry.url)}${sourceText}`,
    };
  }));
}

async function openApiFacts() {
  await access(BUNDLE_PATH).catch(() => {
    throw new Error("generate-agent-front-door: build the Worker first with `npm run build`");
  });
  const worker = await import(`${pathToFileURL(BUNDLE_PATH).href}?front-door=${Date.now()}`);
  if (!worker.app?.fetch) throw new Error("generate-agent-front-door: Worker bundle has no Hono app");
  const response = await worker.app.fetch(
    new Request("https://marquee.stage11.dev/api/openapi.json"),
    { CACHE: {}, DB: {} },
    { waitUntil() {}, passThroughOnException() {} },
  );
  if (!response.ok) throw new Error(`generate-agent-front-door: OpenAPI route returned ${response.status}`);
  const json = await response.text();
  const document = JSON.parse(json);
  const operations = Object.entries(document.paths ?? {}).flatMap(([, methods]) => Object.keys(methods));
  return {
    operations: operations.length,
    digest: createHash("sha256").update(json, "utf8").digest("hex"),
  };
}

async function latencyFacts() {
  try {
    return JSON.parse(await readFile(LATENCY_PATH, "utf8"));
  } catch {
    return { environment: "not-measured", runs: 0, measurements: [] };
  }
}

function renderMachineIndex(manifest) {
  const doors = MACHINE_DOORS.map(([label, url, description]) => `- [${label}](${url}) — ${description}.`);
  const documents = manifest.map((entry) => `- [${entry.source}](${entry.url}) — served from the repository's deliberate document allowlist.`);
  return [...doors, "- Served documents:", ...documents.map((line) => `  ${line}`)].join("\n");
}

function renderSpeed(latency) {
  const measurements = Array.isArray(latency.measurements) ? latency.measurements : [];
  if (measurements.length === 0) {
    return "No committed local measurement is available yet. Run `node scripts/measure-latency.mjs --url <local-worker> --write scripts/latency-baseline.json`; deployed numbers are intentionally not claimed here.";
  }
  const rows = measurements.map((measurement) => `| \`${measurement.path}\` | ${measurement.status} | ${measurement.ttfb_median_ms} ms |`);
  return [
    `Measured with \`scripts/measure-latency.mjs\` over ${latency.runs} runs per surface. Environment: \`${latency.environment}\`.`,
    "",
    "| Surface | HTTP | TTFB median |",
    "| --- | ---: | ---: |",
    ...rows,
    "",
    "These are local evidence, not deployed Cloudflare numbers. Run the same command against the production URL only when an operator authorizes a citable production measurement.",
  ].join("\n");
}

export async function renderFrontDoor() {
  const [manifest, template, api, latency] = await Promise.all([
    readManifest(),
    readFile(TEMPLATE_PATH, "utf8"),
    openApiFacts(),
    latencyFacts(),
  ]);
  const documents = await readSourceDocuments(manifest);
  const commandCount = COMMAND_REGISTRY.length;
  const verbCount = new Set(COMMAND_REGISTRY.map((command) => command.path[0])).size;
  const machineIndex = renderMachineIndex(manifest);
  const speed = renderSpeed(latency);
  const replacements = {
    "{{MACHINE_INDEX}}": machineIndex,
    "{{OPENAPI_OPERATIONS}}": String(api.operations),
    "{{CLI_COMMANDS}}": String(commandCount),
    "{{CLI_VERBS}}": String(verbCount),
    "{{OPENAPI_DIGEST}}": api.digest,
    "{{SPEED}}": speed,
  };
  let llmsText = template;
  for (const [token, value] of Object.entries(replacements)) llmsText = llmsText.replaceAll(token, value);
  if (/\{\{[A-Z_]+\}\}/.test(llmsText)) throw new Error("generate-agent-front-door: unresolved generated token");

  const skill = await readFile(resolve(REPOSITORY_ROOT, "SKILL.md"), "utf8");
  const fullText = [
    GENERATED_BANNER,
    "# Marquee complete machine context\n",
    "This bundle is ordered by the served-document manifest, followed by the installable skill.\n",
    ...documents.flatMap((document) => [
      `\n<!-- Begin ${document.url} · canonical source ${document.source} -->\n`,
      document.servedText,
      `\n<!-- End ${document.url} -->\n`,
    ]),
    "\n<!-- Begin /SKILL.md · canonical source SKILL.md -->\n",
    canonicalHeader("SKILL.md", "/SKILL.md"),
    skill,
    "\n<!-- End /SKILL.md -->\n",
  ].join("");
  return {
    llmsText: `${GENERATED_BANNER}\n${llmsText.trimEnd()}\n`,
    fullText,
    manifest,
    documents,
    facts: { ...api, commandCount, verbCount, latency },
  };
}

export async function writeFrontDoorOutputs(result) {
  await writeFile(LLMS_OUTPUT_PATH, result.llmsText, "utf8");
  await writeFile(FULL_OUTPUT_PATH, result.fullText, "utf8");
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const result = await renderFrontDoor();
  await writeFrontDoorOutputs(result);
  process.stdout.write(`generated ${result.manifest.length + 2} front-door documents\n`);
}
